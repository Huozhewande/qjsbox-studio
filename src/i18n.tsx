export const MESSAGES: Record<Locale, Messages> = { "zh-CN": zh, en };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

interface StudioSettings {
  locale: Locale;
  t: Translate;
}

const StudioContext = createContext<StudioSettings | null>(null);

function translator(messages: Messages): Translate {
  return (key, vars) => messages[key].replace(/\{(\w+)\}/g, (match, name: string) => vars && name in vars ? String(vars[name]) : match);
}

export interface StudioProviderProps {
  locale?: Locale;
  /** Overrides for individual messages, e.g. to rename "rule" to "policy". */
  messages?: Partial<Messages>;
  children: ReactNode;
}

export function StudioProvider({ locale = "zh-CN", messages, children }: StudioProviderProps) {
  const value = useMemo(() => ({ locale, t: translator({ ...MESSAGES[locale], ...messages }) }), [locale, messages]);
  return <StudioContext.Provider value={value}>{children}</StudioContext.Provider>;
}

const fallback: StudioSettings = { locale: "zh-CN", t: translator(zh) };

export function useStudio(): StudioSettings {
  return useContext(StudioContext) ?? fallback;
}

export function useT(): Translate {
  return useStudio().t;
}

/** Translates a known key, or returns `fallbackText` for values outside the dictionary. */
export function tryT(t: Translate, key: string, fallbackText: string): string {
  return key in zh ? t(key as MessageKey) : fallbackText;
}
